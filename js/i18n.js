    normalize(lang) {
      const value = String(lang || '').toLowerCase();
      return value.indexOf('ru') === 0 ? 'ru' : 'en';
    },

    setLanguage(lang) {
      this.lang = this.normalize(lang);
      document.documentElement.lang = this.lang;
      document.title = this.t('meta.title');
      const shell = document.querySelector('.game-shell');
      if (shell) shell.setAttribute('aria-label', this.t('meta.title'));
    },

    t(key, params) {
      const source = this.dictionaries[this.lang] || this.dictionaries.en;
      const fallback = this.dictionaries.en;
      let text = source[key] || fallback[key] || key;
      if (params) {
        Object.keys(params).forEach((name) => {
          text = text.replace(new RegExp('\\{' + name + '\\}', 'g'), params[name]);
        });
      }
      return text;
    }
